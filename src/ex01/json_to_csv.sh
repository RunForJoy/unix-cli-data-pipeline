#!/bin/sh

#  !-f если файл не сущ-т
if [ ! -f "../ex00/hh.json" ]; then 
  echo "Ошибка: файл hh.json не найден в ../ex00/"
  exit 1
fi
# Запускаем фильтрацию
if jq -r -f filter.jq ../ex00/hh.json > hh.csv; then
# -r это сырые данные, то есть ключ убирает «JSON-обертку» и выдает чистый текст - иначе были слеши
  echo "Файл hh.csv успешно создан"
else
  echo "Произошла чудовищная ошибка. Файл не был создан."
fi
