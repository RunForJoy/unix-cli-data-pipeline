#!/bin/bash
INPUT_FILE="../ex03/hh_positions.csv"

if [ ! -f "$INPUT_FILE" ]; then
    echo "Ошибка: Файл $INPUT_FILE не найден."
    exit 1
fi

awk -F',' '
    NR == 1 { 
        header = $0; 
        next; 
    } 
    {
    # создание имени файла из даты во втором столбце
        filename = substr($2, 2, 10) ".csv";

    # Если файл встречается впервые, записываем в него шапку
        if (!(filename in seen)) {
            print header > filename;
            seen[filename] = 1;
        }
        # Дописываем строку данных
        print $0 >> filename;
    }' "$INPUT_FILE"

echo "Созданные файлы:"
ls 2026-*.csv

# awk автоматически читает входной файл построчно - сам цикл под капотом
# $0 это вся строка целиком, включая разделители (запятые) - то есть каждая новая строка
# читаемая awk это $0, если нужен был бы конкретный столбец напр $1 - первый
# substr($2, 2, 10) — вырезаем 10 символов из строки во 2м столбце ($2), 
# начиная со 2го символа (без кавычек чтобы)
# В awk не нужно заранее объявлять переменные и массивы, потому что они
# создаются автоматически при первом использовании.
# то есть на этапе проверки условия filename in seen создается пустой
# массив seen в которм мы не находим ключа filename
# ещё до присваивания seen[filename] = 1.
# seen[filename] = 1 ассоциативный массив, но как словарь в питон
# filename in seen — проверяет, существует ли ключ filename в массиве seen
# общая схема вызова awk: 'скрипт' входной_файл ( в кавычках если это имя переменной
# как у меня "$INPUT_FILE")