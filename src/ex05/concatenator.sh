#!/bin/bash

# записываем в переменную результат команды ls: все файлы согласно шаблону (дата.csv)
# если файлов не найдем то перенаправим ошибку в бесконечность))
FILES=$(ls [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9].csv 2>/dev/null)

# флаг -z (zero) проверяет, является ли длина строки нулевой.
if [ -z "$FILES" ]; then
    echo "Нет файлов для объединения"
    exit 1
fi

# Узнаем имя первого файла
FIRST_FILE=$(echo "$FILES" | head -n 1)
# Открываем этот файл, берем первую строку и записываем в hh_positions.csv
head -n 1 "$FIRST_FILE" > hh_positions.csv

# 3. Добавляем данные из всех найденных файлов
for f in $FILES; do
    tail -n +2 "$f" >> hh_positions.csv
done

echo "Все файлы объединены в hh_positions.csv"

# 
# /dev/null — это «черная дыра» в Linux. Всё, что туда отправляется, исчезает навсегда
# cинтаксис VARIABLE=$(команда) в bash называется подстановкой команды (command substitution)
# он означает: «выполни команду внутри скобок и сохрани её результат в переменную»
# echo "$ПЕРЕМЕННАЯ" | head -n 1 — прочитай первую строчку из этого текста
# head "$ПЕРЕМЕННАЯ" — открой файл, путь к которому написан в переменной, и прочитай его первую строку
