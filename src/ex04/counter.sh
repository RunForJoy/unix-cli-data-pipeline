#!/bin/sh

INPUT_FILE="../ex03/hh_positions.csv"
OUTPUT_FILE="hh_uniq_positions.csv"

# Проверка существования входного файла
if [ ! -f "$INPUT_FILE" ]; then
  echo "Ошибка: файл $INPUT_FILE не найден."
  exit 1
fi

# Создаем выходной файл с заголовком
echo '"name","count"' > "$OUTPUT_FILE"

# Обработка данных
tail -n +2 "$INPUT_FILE" |          # 1. Пропускаем заголовок
cut -d',' -f3 |                      # 2. Берем 3-е поле (name)
sed 's/"//g' |                       # 3. Удаляем кавычки
sort |                               # 4. Сортируем для uniq
uniq -c |                            # 5. Подсчитываем уникальные значения
sort -rn |                           # 6. Сортируем по убыванию числа
awk '{print "\"" $2 "\"," $1}' >> "$OUTPUT_FILE"  # 7. Форматируем в CSV

echo "Обработка завершена. Результат сохранён в $OUTPUT_FILE"

# cut -d',' delimiter запятая, -f3 - field 3, cut вырезать
# sed - stream editor s - substitute, т.е замена
# / после первого разделителя указыввем что заменяем, то есть ", 
# между вторым и третьим слешем указываем на что заменям - то есть на пустоту
# флаг g - global, т.е все кавычки во всей строке
# sort сортируем строки в алфавитном порядке
# считаем уникальные значения. (uniq - оставляет уник строку без дубликатов, c - count)
# unic видит» повторы только в том случае, если они стоят рядом, поэтому делали sort сначала
# sort -rn обратная сортировка по кол-ву
